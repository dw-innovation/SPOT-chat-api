"""What the assistant declines, and what the query format cannot express.

The two tables below feed the system prompt, the `decline` and
`report_limitations` tools and the fields of the API response, so the three
cannot drift apart. Replies to harmful requests are fixed texts written here,
not generated by the model.
"""

