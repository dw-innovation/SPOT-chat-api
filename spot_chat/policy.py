# Spatial terms whose direction is lost when they become a distance.
DIRECTIONAL_TERMS = frozenset(SPATIAL_TERM_TABLE["1500 m"]) | {"in front of", "behind", "right of", "left of"}


def limitation(category, detail="") -> dict:
    """One entry of the `limitations` list: the category, the user's wording and what to show."""
    limit = LIMITS.get(str(category or "").strip().lower())
    if limit is None:
        raise ValueError(f"unknown category '{category}'; use one of {', '.join(LIMITS)}")
    return {"category": limit.name, "detail": " ".join(str(detail or "").split())[:200],
            "message": limit.message}


def merge_limitations(existing: list[dict], new: list[dict]) -> list[dict]:
    """Append `new`, skipping what is already there (the model and the tools may both report
    the same part, with slightly different wording)."""
    merged = list(existing)
    for item in new:
        detail = item["detail"].lower()
        if not any(old["category"] == item["category"]
                   and (detail in old["detail"].lower() or old["detail"].lower() in detail)
                   for old in merged):
            merged.append(item)
    return merged


def code_limits(before: dict, after: dict) -> list[dict]:
    """Limits the tools can see without the model: a direction that became a plain distance,
    and a query that grew beyond the supported size."""
    def terms(query):
        return {r.get("spatial_term") for r in query["relations"]} & DIRECTIONAL_TERMS

    def too_big(query):
        return (len(query["entities"]) > MAX_ENTITIES
                or any(len(e.get("properties", [])) > MAX_PROPERTIES for e in query["entities"]))

    found = [limitation("direction", term) for term in sorted(terms(after) - terms(before))]
    if too_big(after) and not too_big(before):
        found.append(limitation("too_many"))
    return found


def limit_hints(message: str) -> list[tuple[Limit, str]]:
    """Limits the user's wording points to, with the matching words."""
    hints = []
    for limit in LIMITS.values():
        match = limit.pattern.search(message) if limit.pattern else None
        if match:
            hints.append((limit, " ".join(match.group(0).split())))
    return hints


# --------------------------------------------------------------------------- #
# Prompt sections
# --------------------------------------------------------------------------- #

def refusal_prompt() -> str:
    return "\n".join(f"- {c.name}: {c.when}." for c in REFUSAL_CATEGORIES.values())


def limits_prompt() -> str:
    return "\n".join(
        f"- {limit.name} ({limit.examples}): {limit.message} -> {limit.instead}"
        for limit in LIMITS.values() if limit.instead
    )
