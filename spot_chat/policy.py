_UNIT = r"(?:m|km|mi|yd|ft|meters?|metres?|kilometers?|kilometres?|miles?|yards?|feet)"


@dataclass(frozen=True)
class Limit:
    name: str
    examples: str              # how users phrase it
    message: str               # shown to the user (API field `limitations[].message`)
    instead: str = ""          # what the model builds instead; empty = not listed in the prompt
    pattern: re.Pattern | None = None    # light scan of the user message, English only


def _scan(pattern: str) -> re.Pattern:
    return re.compile(pattern, re.IGNORECASE)


